def _has_vector_extension() -> bool:
    """判断当前库是否已启用 ``vector`` 扩展。"""
    conn = op.get_bind()
    return bool(
        conn.execute(
            sa.text("SELECT 1 FROM pg_extension WHERE extname = 'vector'")
        ).scalar()
    )


def _month_bounds(offset: int) -> tuple[datetime, datetime]:
    """返回相对当前月的第 ``offset`` 个月的区间边界。

    Args:
        offset: 月份偏移，``-1`` 表示上月，``0`` 表示本月，``1`` 表示下月。

    Returns:
        ``(区间起, 区间止)``，均为 UTC 时区。
    """
    today = datetime.now(UTC).date()
    year = today.year
    month = today.month + offset
    while month <= 0:
        month += 12
        year -= 1
    while month > 12:
        month -= 12
        year += 1
    start = datetime(year, month, 1, tzinfo=UTC)
    if month == 12:
        end = datetime(year + 1, 1, 1, tzinfo=UTC)
    else:
        end = datetime(year, month + 1, 1, tzinfo=UTC)
    return start, end


def _create_month_partition(offset: int) -> None:
    """创建一个按月的 RANGE 分区。"""
    start, end = _month_bounds(offset)
    name = f"exposure_log_{start.year}_{start.month:02d}"
    op.execute(
        sa.text(
            f"CREATE TABLE IF NOT EXISTS {name} PARTITION OF exposure_log "
            f"FOR VALUES FROM ('{start.isoformat()}') TO ('{end.isoformat()}')"
        )
    )


